def _fmt(value: float, digits: int = 4) -> str:
    return f"{value:.{digits}f}"


def _fmt_p(p: float) -> str:
    """Report very small p-values as an inequality instead of a rounded 0.000."""
    if p < 0.001:
        return "$<0.001$"
    return f"{p:.3f}"


def _holm(p_values: list[float]) -> list[float]:
    """Holm-Bonferroni adjusted p-values (step-down, monotone, clipped to 1)."""
    m = len(p_values)
    order = sorted(range(m), key=lambda i: p_values[i])
    adjusted = [0.0] * m
    running = 0.0
    for rank, idx in enumerate(order):
        candidate = min(1.0, (m - rank) * p_values[idx])
        running = max(running, candidate)
        adjusted[idx] = running
    return adjusted


def write_significance_table(payload: dict, path: Path) -> Path:
    """One table with two panels: bootstrap CIs + ECE, and paired comparisons."""
    lines = [
        "% AUTO-GENERATED by scripts/06_analyze_significance.py - do not edit by hand.",
        "\\begin{table}[t]",
        "\\centering",
        "\\footnotesize",
        "\\setlength{\\tabcolsep}{2pt}",
        "\\caption{Post-hoc statistics on the frozen test predictions. "
        "\\emph{Top:} accuracy and macro-F1 with 95\\% percentile bootstrap "
        f"intervals ({payload['n_boot']:,} resamples of the {payload['num_test']:,} "
        "test items) and the top-label expected calibration error (ECE, 10 bins). "
        "\\emph{Bottom:} paired comparisons, $A$ minus $B$, with a 95\\% paired-bootstrap "
        "interval on macro-F1; $p_{\\text{F1}}$ is the paired-bootstrap $p$-value and "
        "$p_{\\text{acc}}$ the exact two-sided McNemar $p$-value on the two systems' "
        "correctness. $^{\\dagger}$ marks $p<0.05$ after a Holm--Bonferroni correction "
        "over the seven comparisons below; values below $0.001$ are shown as "
        "$<0.001$. No macro-F1 gap is significant; the only differences that survive "
        "correction are the two accuracy gaps involving M6, discussed in the text.}",
        "\\label{tab:significance}",
        "\\label{tab:confidence}",
        "\\begin{tabular}{lcccc}",
        "\\toprule",
        "System & Acc. [95\\% CI] & M-F1 [95\\% CI] & ECE & \\\\",
        "\\midrule",
    ]
    for name in payload["models"]:
        entry = payload["confidence"][name]
        label = entry["label"]
        acc, mf1 = entry["accuracy"], entry["macro_f1"]
        ece = entry["calibration"]["ece"]
        lines.append(
            f"{label} & {_fmt(acc['point'])} [{_fmt(acc['ci_low'])}, {_fmt(acc['ci_high'])}] "
            f"& {_fmt(mf1['point'])} [{_fmt(mf1['ci_low'])}, {_fmt(mf1['ci_high'])}] "
            f"& {ece:.3f} & \\\\"
        )
    lines += [
        "\\midrule",
        "$A-B$ & $\\Delta$M-F1 [95\\% CI] & $p_{\\text{F1}}$ "
        "& $\\Delta$Acc & $p_{\\text{acc}}$ \\\\",
        "\\midrule",
    ]
    p_f1_holm = _holm([pair["macro_f1"]["p_value"] for pair in payload["pairs"]])
    p_acc_holm = _holm([pair["mcnemar"]["p_value"] for pair in payload["pairs"]])
    for idx, pair in enumerate(payload["pairs"]):
        d = pair["macro_f1"]
        da = pair["accuracy"]
        mcn = pair["mcnemar"]
        comp = f"{pair['label_a']} $-$ {pair['label_b']}"
        p_f1 = _fmt_p(d["p_value"]) + ("$^{\\dagger}$" if p_f1_holm[idx] < 0.05 else "")
        p_acc = _fmt_p(mcn["p_value"]) + ("$^{\\dagger}$" if p_acc_holm[idx] < 0.05 else "")
        lines.append(
            f"{comp} & {d['delta']:+.4f} [{d['ci_low']:+.4f}, {d['ci_high']:+.4f}] "
            f"& {p_f1} & {da['delta']:+.4f} & {p_acc} \\\\"
        )
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")
    return path


def write_training_details_table(path: Path) -> Path:
    """Hyperparameter / validation summary, read from each ``training_summary.json``."""
    root = PROJECT_ROOT / "outputs" / "evaluation" / "per_model"
    rows = []
    for name in MODEL_ORDER:
        summary = json.loads((root / name / "training_summary.json").read_text(encoding="utf-8"))
        training = summary["training"]
        stages = training["stages"]["stages"]
        # The first stage starts from the encoder checkpoint when one is set in the
        # resolved config (``stages[0].init_from`` is only filled for chained
        # in-run stages).  Read the authoritative per-model config for it.
        config_path = root / name / "config.yaml"
        encoder_checkpoint = ""
        if config_path.is_file():
            import yaml

            cfg = yaml.safe_load(config_path.read_text(encoding="utf-8"))
            encoder_checkpoint = str(cfg.get("encoder_checkpoint") or "")
        init = (stages[0].get("init_from") or encoder_checkpoint or "").replace("\\", "/")
        if not init:
            init_label = "pre-trained"
        elif "customdlr2stage/run_001/stage_checkpoints/stage_1" in init:
            init_label = "M3 stage-1"
        elif "customdlr2stage/run_001/best_model" in init:
            init_label = "M3 best"
        elif "sensitiveai-vi/run_001/best_model" in init:
            init_label = "M1 best"
        else:
            init_label = "chained"
        weight_tag = stages[0]["loss"].get("class_weight")
        weight_kind = {
            "inverse_sqrt_frequency": "inv-sqrt",
            "inverse_frequency": "inv-freq",
            "manual": "manual",
            None: "none",
        }.get(weight_tag, "none")
        if not stages[0]["loss"].get("use_class_weight"):
            weight_kind = "none"
        losses = [{"cross_entropy": "CE", "focal": "focal", "concept": "concept"}.get(s["loss"]["type"], s["loss"]["type"]) for s in stages]
        if len(losses) > 1:
            loss = " $\\to$ ".join(dict.fromkeys(losses))
        else:
            loss = losses[0]
        rows.append(
            {
                "label": MODEL_LABELS[name],
                "init": init_label,
                "stages": training["stages"]["num_stages"],
                "loss": loss,
                "weight": weight_kind,
                "best_epoch": training["best_epoch"],
                "best_stage": training["best_stage"],
                "epochs_run": training["epochs_run"],
                "val_macro_f1": training["best_value"],
            }
        )

    lines = [
        "% AUTO-GENERATED by scripts/06_analyze_significance.py - do not edit by hand.",
        "\\begin{table}[t]",
        "\\centering",
        "\\small",
        "\\setlength{\\tabcolsep}{4pt}",
        "\\caption{Training configuration and the validation checkpoint that was "
        "frozen for the test pass (M1--M6, Sect.~\\ref{sec:chain}). AdamW, linear "
        "schedule, effective batch size 32 and sequence length 256 are shared by all "
        "systems. ``init`` is the encoder the first stage starts from; ``best ep.`` "
        "is the epoch whose validation macro-F1 was highest (it can lie in an earlier "
        "stage).}",
        "\\label{tab:training-details}",
        "\\begin{tabular}{lcccccc}",
        "\\toprule",
        "System & init & stages & loss & class w. & best ep. & val M-F1 \\\\",
        "\\midrule",
    ]
    for row in rows:
        stage_tag = ""
        if row["stages"] > 1:
            stage_tag = {"single": "", "stage_1": "\\,(s1)", "stage_2": "\\,(s2)", "stage_3": "\\,(s3)", "stage_1_ext": "\\,(s1)"}.get(
                row["best_stage"], ""
            )
        lines.append(
            f"{row['label']} & {row['init']} & {row['stages']} & {row['loss']} "
            f"& {row['weight']} & {row['best_epoch']}{stage_tag} & {_fmt(row['val_macro_f1'])} \\\\"
        )
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")
    return path


def plot_confusion_matrices(models, path: Path, per_model_root: Path | None = None) -> Path:
    """Row-normalised 3x3 confusion matrices for M1, M3 and M6 in one row."""
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    from src.evaluation.plots import setup_style

    frames = load_predictions(models, per_model_root)
    setup_style()
    fig, axes = plt.subplots(1, 3, figsize=(8.6, 2.9), constrained_layout=True)
    chosen = [
        ("sensitiveai-vi", "M1 baseline"),
        ("sensitiveai-vi-customdlr2stage", "M3 full recipe"),
        ("sensitiveai-vi-stage2", "M6 stage-2 only"),
    ]
    for ax, (name, label) in zip(axes, chosen):
        frame = frames[name]
        y_true = frame["true_label_id"].to_numpy()
        y_pred = frame["pred_label_id"].to_numpy()
        cm = np.zeros((3, 3))
        for t in range(3):
            for p in range(3):
                cm[t, p] = np.sum((y_true == t) & (y_pred == p))
        norm = cm / np.maximum(cm.sum(axis=1, keepdims=True), 1)
        im = ax.imshow(norm, cmap="Blues", vmin=0, vmax=1)
        for t in range(3):
            for p in range(3):
                ax.text(
                    p, t, f"{norm[t, p]:.2f}", ha="center", va="center",
                    color="white" if norm[t, p] > 0.55 else "black", fontsize=7.5,
                )
        ax.set_xticks(range(3))
        ax.set_yticks(range(3))
        ax.set_xticklabels(["HATE", "OFF.", "CLEAN"], fontsize=7)
        ax.set_yticklabels(["HATE", "OFF.", "CLEAN"], fontsize=7)
        ax.set_xlabel("Predicted", fontsize=8)
        ax.set_title(label, fontsize=9)
        ax.grid(False)
    axes[0].set_ylabel("Actual", fontsize=8)
    fig.colorbar(im, ax=axes, fraction=0.025, pad=0.02, label="row-normalised")
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path, dpi=200)
    plt.close(fig)
    return path


def write_markdown(payload: dict, path: Path) -> Path:
    lines = [
        "# Post-hoc statistical analysis",
        "",
        f"- test items: {payload['num_test']:,}",
        f"- bootstrap resamples: {payload['n_boot']:,} (seed {payload['seed']})",
        "",
        "## Confidence intervals",
        "",
        "| System | Accuracy [95% CI] | Macro-F1 [95% CI] | HATE F1 | OFF. F1 | ECE |",
        "|---|---|---|---|---|---|",
    ]
    for name in payload["models"]:
        e = payload["confidence"][name]
        acc, mf1 = e["accuracy"], e["macro_f1"]
        lines.append(
            f"| {e['label']} | {acc['point']:.4f} [{acc['ci_low']:.4f}, {acc['ci_high']:.4f}] "
            f"| {mf1['point']:.4f} [{mf1['ci_low']:.4f}, {mf1['ci_high']:.4f}] "
            f"| {e['HATE_f1']['point']:.4f} | {e['OFFENSIVE_f1']['point']:.4f} "
            f"| {e['calibration']['ece']:.3f} |"
        )
    lines += ["", "## Paired comparisons (paired bootstrap + McNemar)", "",
              "| A - B | dMF1 [95% CI] | p_F1 (bootstrap) | dAcc | p_acc (McNemar) | p_acc (Holm) | b/c |",
              "|---|---|---|---|---|---|---|"]
    p_acc_holm = _holm([pair["mcnemar"]["p_value"] for pair in payload["pairs"]])
    for idx, pair in enumerate(payload["pairs"]):
        d = pair["macro_f1"]
        da = pair["accuracy"]
        m = pair["mcnemar"]
        lines.append(
            f"| {pair['label_a']}-{pair['label_b']} | {d['delta']:+.4f} "
            f"[{d['ci_low']:+.4f}, {d['ci_high']:+.4f}] | {_fmt_p(d['p_value'])} "
            f"| {da['delta']:+.4f} "
            f"| {_fmt_p(m['p_value'])} | {_fmt_p(p_acc_holm[idx])} "
            f"| {m['a_correct_b_wrong']}/{m['a_wrong_b_correct']} |"
        )
    lines += ["", "## Error stratification (M3)", "",
              "| stratum | n | acc | macro-F1 | HATE recall | OFF. recall |", "|---|---|---|---|---|---|"]
    for tag, entry in sorted(payload["error_stratification"]["sensitiveai-vi-customdlr2stage"].items()):
        pc = entry["per_class"]
        lines.append(
            f"| {tag} | {entry['count']} | {entry['accuracy']:.4f} | {entry['macro_f1']:.4f} "
            f"| {pc['HATE']['recall']:.3f} | {pc['OFFENSIVE']['recall']:.3f} |"
        )
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


def main() -> int:
    payload = analyse(MODEL_ORDER, n_boot=10000, seed=42)
    save_analysis(payload, ANALYSIS_DIR / "significance_summary.json")
    write_markdown(payload, ANALYSIS_DIR / "significance_report.md")
    write_significance_table(payload, TABLES_DIR / "significance.tex")
    write_training_details_table(TABLES_DIR / "training_details.tex")
    plot_confusion_matrices(MODEL_ORDER, FIGURES_DIR / "confusion_matrices.png")
    (TABLES_DIR / "confidence_intervals.tex").unlink(missing_ok=True)

    # mirror into the generated copy under outputs/paper so both stay in sync
    mirror = PROJECT_ROOT / "outputs" / "paper"
    for rel in ("tables/significance.tex", "tables/training_details.tex", "figures/confusion_matrices.png"):
        src = PAPER_DIR / rel
        dst = mirror / rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        dst.write_bytes(src.read_bytes())
    print("wrote", PAPER_DIR)
    return 0


if __name__ == "__main__":
    sys.exit(main())
