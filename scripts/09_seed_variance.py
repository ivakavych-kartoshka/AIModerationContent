"""Step 9 - multi-seed reruns of the six systems (seed-variance study).

    python scripts/09_seed_variance.py --seeds 42 43 44 45 46
    python scripts/09_seed_variance.py --seeds 43 --models sensitiveai-vi
    python scripts/09_seed_variance.py --seeds 42 43 --dry-run

Why a dedicated script
----------------------
The six systems are not independent: M3 chains from M2, M4 from M3, M5 from
M2 + M3's stage-1 checkpoint and M6 from M1 (see ``configs/*.yaml``).  A plain
``for seed`` loop over ``01_train_all.py`` would let a later seed chain from an
*earlier* seed's checkpoint (``resolve_encoder_checkpoint`` falls back to the
newest run of the producing model), which silently mixes seeds and invalidates
the study.

This script therefore re-generates a per-seed config for every model, rewrites
the chained paths (``encoder_checkpoint`` and every literal ``stages[*].init_from``)
to point at the run *this seed just produced*, then trains and evaluates.  Each
seed is a self-contained lineage, so the only thing that changes between seeds is
``seed``.

Outputs
-------
* ``outputs/seeds/seed_<S>/configs/<model>.yaml``  - the resolved per-seed config
* runs in the normal ``outputs/reports/<model>/run_XXX`` tree (new run ids)
* evaluation mirrors/logs under ``outputs/seeds/seed_<S>/evaluation`` so the
  primary ``outputs/evaluation`` artefacts are left untouched
* ``outputs/seeds/seed_<S>/seed_summary.json``  - per-model metrics for that seed
* ``outputs/seeds/seed_variance_summary.json`` + ``.md`` - mean +/- std per model
"""

from __future__ import annotations

import argparse
import json
import statistics
import sys
import time
from pathlib import Path
from typing import Any, Dict, List, Optional

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from src.common.config import dump_json, dump_yaml, load_yaml, resolve_config_path  # noqa: E402
from src.common.logging_utils import get_logger  # noqa: E402
from src.common.paths import (  # noqa: E402
    experiment_dir,
    next_run_id,
    project_relative,
    report_dir,
)
from src.evaluation.run_evaluation import build_parser as eval_parser  # noqa: E402
from src.evaluation.run_evaluation import run as eval_run  # noqa: E402
from src.training.run_experiment import build_parser as train_parser  # noqa: E402
from src.training.run_experiment import run as train_run  # noqa: E402

LOGGER = get_logger("sensitiveai.seed_variance")

#: Training order - every model only depends on models earlier in this list.
PIPELINE: tuple[str, ...] = (
    "sensitiveai-vi",
    "sensitiveai-vi-custom",
    "sensitiveai-vi-customdlr2stage",
    "sensitiveai-vi-custom-curriculum",
    "sensitiveai-vi-customdlr2stage-ext",
    "sensitiveai-vi-stage2",
)

#: ``encoder_checkpoint`` -> producing model (its ``best_model/`` of this seed).
ENCODER_FROM: Dict[str, str] = {
    "sensitiveai-vi-customdlr2stage": "sensitiveai-vi-custom",
    "sensitiveai-vi-custom-curriculum": "sensitiveai-vi-customdlr2stage",
    "sensitiveai-vi-customdlr2stage-ext": "sensitiveai-vi-custom",
}

#: literal ``stages[0].init_from`` -> (producing model, "report"|"experiment", subpath)
STAGE_INIT_FROM: Dict[str, tuple[str, str, str]] = {
    "sensitiveai-vi-customdlr2stage-ext": (
        "sensitiveai-vi-customdlr2stage",
        "experiment",
        "stage_checkpoints/stage_1",
    ),
    "sensitiveai-vi-stage2": ("sensitiveai-vi", "report", "best_model"),
}

DEFAULT_SEEDS = (42, 43, 44, 45, 46)

METRIC_KEYS = (
    "accuracy",
    "macro_f1",
    "weighted_f1",
    "macro_precision",
    "macro_recall",
    "HATE_f1",
    "OFFENSIVE_f1",
    "CLEAN_f1",
    "macro_roc_auc",
)


def build_seed_config(model: str, seed: int, lineage: Dict[str, Dict[str, Path]], out_dir: Path) -> Path:
    """Rewrite one model's config so every chained path points at this seed."""
    cfg = load_yaml(resolve_config_path(f"configs/{model}.yaml"))
    cfg["seed"] = seed

    if model in ENCODER_FROM:
        src = ENCODER_FROM[model]
        if src not in lineage:
            raise RuntimeError(f"{model} needs '{src}' for seed {seed}, which has not run yet")
        cfg["encoder_checkpoint"] = (lineage[src]["report"] / "best_model").as_posix()
    elif "encoder_checkpoint" in cfg:
        cfg["encoder_checkpoint"] = None

    if model in STAGE_INIT_FROM:
        src, kind, rel = STAGE_INIT_FROM[model]
        if src not in lineage:
            raise RuntimeError(f"{model} needs '{src}' for seed {seed}, which has not run yet")
        stages = cfg.get("stages") or []
        if not stages:
            raise RuntimeError(f"{model} declares STAGE_INIT_FROM but has no 'stages' list")
        stages[0]["init_from"] = (lineage[src][kind] / rel).as_posix()

    header = (
        f"# Per-seed config of {model} for seed={seed}\n"
        f"# Generated by scripts/09_seed_variance.py - do not edit by hand.\n"
    )
    return dump_yaml(cfg, out_dir / f"{model}.yaml", header=header)


def planned_paths(model: str) -> Dict[str, Path]:
    """Where this model *would* run next (used only by ``--dry-run``)."""
    run_id = next_run_id(model)
    return {
        "report": Path(project_relative(report_dir(model, run_id))),
        "experiment": Path(project_relative(experiment_dir(model, run_id))),
    }


def read_metrics(report_dir: Path) -> Dict[str, Any]:
    metrics_path = report_dir / "metrics.json"
    if not metrics_path.is_file():
        return {}
    payload = json.loads(metrics_path.read_text(encoding="utf-8"))
    return {k: payload.get(k) for k in METRIC_KEYS if payload.get(k) is not None}


def run_seed(seed: int, models: List[str], root: Path, dry_run: bool, skip_eval: bool) -> Dict[str, Any]:
    seed_dir = root / f"seed_{seed}"
    cfg_dir = seed_dir / "configs"
    eval_dir = seed_dir / "evaluation"

    LOGGER.info("=" * 78)
    LOGGER.info("SEED %d  ->  %s", seed, project_relative(seed_dir))
    LOGGER.info("=" * 78)

    lineage: Dict[str, Dict[str, Path]] = {}
    rows: List[Dict[str, Any]] = []

    for index, model in enumerate(models, start=1):
        LOGGER.info("")
        LOGGER.info("#" * 78)
        LOGGER.info("# [seed %d | %d/%d] %s", seed, index, len(models), model)
        LOGGER.info("#" * 78)

        cfg_path = build_seed_config(model, seed, lineage, cfg_dir)

        if dry_run:
            lineage[model] = planned_paths(model)
            LOGGER.info(
                "[dry-run] %s -> %s (config: %s)",
                model,
                project_relative(lineage[model]["report"]),
                project_relative(cfg_path),
            )
            continue

        train_argv = ["--config", str(cfg_path)]
        args = train_parser().parse_args(train_argv)

        started = time.perf_counter()
        summary = train_run(args)
        run_report = Path(summary["report_dir"])
        run_experiment = Path(summary["experiment_dir"])
        run_id = summary["run_id"]
        lineage[model] = {"report": run_report, "experiment": run_experiment}

        row: Dict[str, Any] = {
            "seed": seed,
            "model": model,
            "run_id": run_id,
            "report_dir": project_relative(run_report),
            "train_seconds": round(time.perf_counter() - started, 1),
        }

        if not skip_eval:
            eval_args = eval_parser().parse_args(
                ["--model", model, "--run-id", run_id, "--eval-dir", str(eval_dir)]
            )
            eval_run(eval_args)
            row.update(read_metrics(run_report))

        rows.append(row)
        LOGGER.info("[seed %d] %s done (run=%s) in %.1fs", seed, model, run_id, row["train_seconds"])

    if dry_run:
        return {"seed": seed, "rows": []}

    payload = {"seed": seed, "models": models, "rows": rows}
    dump_json(payload, seed_dir / "seed_summary.json")
    return payload


def aggregate(seed_payloads: List[Dict[str, Any]]) -> Dict[str, Any]:
    """Mean/std of every metric, per model, across the seeds that produced one."""
    per_model: Dict[str, Dict[str, List[float]]] = {}
    for payload in seed_payloads:
        for row in payload.get("rows", []):
            bucket = per_model.setdefault(row["model"], {})
            for key in METRIC_KEYS:
                value = row.get(key)
                if isinstance(value, (int, float)):
                    bucket.setdefault(key, []).append(float(value))

    summary: Dict[str, Any] = {}
    for model, metrics in per_model.items():
        summary[model] = {
            "n_seeds": max((len(v) for v in metrics.values()), default=0),
            "mean": {k: round(statistics.fmean(v), 6) for k, v in metrics.items()},
            "std": {
                k: round(statistics.stdev(v), 6) if len(v) > 1 else 0.0
                for k, v in metrics.items()
            },
        }
    return summary


def write_markdown(summary: Dict[str, Any], path: Path, seeds: List[int]) -> None:
    lines = [
        "# Seed-variance summary",
        "",
        f"Seeds: {', '.join(map(str, seeds))}",
        "",
        "| Model | n | Acc. (mean±std) | Macro-F1 (mean±std) | HATE-F1 (mean±std) | ROC-AUC (mean±std) |",
        "|---|---|---|---|---|---|",
    ]
    for model in PIPELINE:
        if model not in summary:
            continue
        block = summary[model]
        mean, std = block["mean"], block["std"]

        def fmt(key: str) -> str:
            if key not in mean:
                return "-"
            return f"{mean[key]:.4f} ± {std[key]:.4f}"

        lines.append(
            f"| {model} | {block['n_seeds']} | {fmt('accuracy')} | {fmt('macro_f1')} "
            f"| {fmt('HATE_f1')} | {fmt('macro_roc_auc')} |"
        )
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main(argv: Optional[List[str]] = None) -> int:
    argv = list(argv if argv is not None else sys.argv[1:])

    parser = argparse.ArgumentParser(
        prog="python scripts/09_seed_variance.py",
        description="Retrain the six systems under several seeds, as a seed-variance study.",
    )
    parser.add_argument("--seeds", nargs="*", type=int, default=list(DEFAULT_SEEDS))
    parser.add_argument("--models", nargs="*", default=list(PIPELINE), choices=list(PIPELINE))
    parser.add_argument("--out-dir", default="outputs/seeds", help="Where to write per-seed configs/results.")
    parser.add_argument("--dry-run", action="store_true", help="Write the per-seed configs and stop.")
    parser.add_argument("--skip-eval", action="store_true", help="Train only; do not score the test split.")
    args = parser.parse_args(argv)

    models = [m for m in PIPELINE if m in args.models]  # keep dependency order
    root = Path(args.out_dir).resolve()

    LOGGER.info("Seed-variance study: %d seed(s) x %d model(s)", len(args.seeds), len(models))
    LOGGER.info("  seeds  : %s", ", ".join(map(str, args.seeds)))
    LOGGER.info("  models : %s", ", ".join(models))

    payloads = [
        run_seed(seed, models, root, args.dry_run, args.skip_eval)
        for seed in args.seeds
    ]

    if args.dry_run:
        LOGGER.info("[seed_variance] dry run - stopping before training.")
        return 0

    summary = aggregate(payloads)
    dump_json(
        {"seeds": args.seeds, "models": models, "per_model": summary},
        root / "seed_variance_summary.json",
    )
    write_markdown(summary, root / "seed_variance_summary.md", args.seeds)

    LOGGER.info("=" * 78)
    LOGGER.info("Seed-variance summary (mean +/- std over %d seed(s))", len(args.seeds))
    for model, block in summary.items():
        mean, std = block["mean"], block["std"]
        LOGGER.info(
            "  %-38s n=%d  Acc=%.4f+/-%.4f  M-F1=%.4f+/-%.4f",
            model, block["n_seeds"],
            mean.get("accuracy", float("nan")), std.get("accuracy", 0.0),
            mean.get("macro_f1", float("nan")), std.get("macro_f1", 0.0),
        )
    LOGGER.info("=" * 78)
    LOGGER.info("Artefacts: %s", project_relative(root))
    return 0


if __name__ == "__main__":
    sys.exit(main())
