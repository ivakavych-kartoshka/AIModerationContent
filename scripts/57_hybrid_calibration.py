# --------------------------------------------------------------------------- #
# Calibration helpers
# --------------------------------------------------------------------------- #
def brier_score(proba: np.ndarray, y_true: np.ndarray) -> float:
    """Multiclass Brier score = mean_k (1/N) sum_i (p_ik - onehot_ik)^2."""
    onehot = np.zeros_like(proba)
    onehot[np.arange(len(y_true)), y_true] = 1.0
    return float(np.mean(np.sum((proba - onehot) ** 2, axis=1)))


def negative_log_likelihood(proba: np.ndarray, y_true: np.ndarray) -> float:
    picked = proba[np.arange(len(y_true)), y_true]
    picked = np.clip(picked, 1e-12, 1.0)
    return float(-np.mean(np.log(picked)))


def compute_ece(proba: np.ndarray, y_true: np.ndarray, n_bins: int = 10) -> float:
    """Expected Calibration Error (standard, 10 equal‑width bins)."""
    confidence = proba.max(axis=1)
    prediction = proba.argmax(axis=1)
    correctness = (prediction == y_true).astype(float)
    n_items = int(proba.shape[0])
    edges = np.linspace(0.0, 1.0, n_bins + 1)
    ece = 0.0
    for i in range(n_bins):
        lo, hi = float(edges[i]), float(edges[i + 1])
        if i == 0:
            mask = (confidence > lo) & (confidence <= hi)
        else:
            mask = (confidence > lo) & (confidence <= hi)
        count = int(mask.sum())
        if count > 0:
            accuracy = correctness[mask].mean()
            avg_conf = confidence[mask].mean()
            ece += (count / n_items) * abs(accuracy - avg_conf)
    return float(ece)


def reliability_bins(proba: np.ndarray, y_true: np.ndarray, n_bins: int = 10) -> List[Dict[str, float]]:
    confidence = proba.max(axis=1)
    prediction = proba.argmax(axis=1)
    correctness = (prediction == y_true).astype(float)
    edges = np.linspace(0.0, 1.0, n_bins + 1)
    bins: List[Dict[str, float]] = []
    for i in range(n_bins):
        lo, hi = edges[i], edges[i + 1]
        if i == 0:
            mask = (confidence > lo) & (confidence <= hi)
        else:
            mask = (confidence > lo) & (confidence <= hi)
        count = int(mask.sum())
        bins.append(
            {
                "low": float(lo),
                "high": float(hi),
                "count": count,
                "confidence": float(confidence[mask].mean()) if count else 0.0,
                "accuracy": float(correctness[mask].mean()) if count else 0.0,
            }
        )
    return bins


# --------------------------------------------------------------------------- #
# Dataset loading helpers
# --------------------------------------------------------------------------- #
def load_vihsd_fusion() -> Dict[str, np.ndarray]:
    """Return AI‑only probs and hybrid fused probs for ViHSD test."""
    p = FUSION_DIR / "sensitiveai-vi-custom" / "fusion_predictions.csv"
    df = pd.read_csv(p, encoding="utf-8")
    lab = {"HATE": 0, "OFFENSIVE": 1, "CLEAN": 2}
    y = df["true_label"].map(lab).to_numpy(dtype=int)

    # AI‑only probabilities
    p_ai = df[["prob_HATE", "prob_OFFENSIVE", "prob_CLEAN"]].to_numpy(dtype=float)

    # Hybrid fused probabilities (primary variant)
    p_fuse = df[["fused_hate", "fused_offensive", "fused_clean"]].to_numpy(dtype=float)

    return {"y": y, "p_ai": p_ai, "p_fuse": p_fuse}


def load_mixed_e2e() -> Dict[str, np.ndarray]:
    """Return AI‑only and hybrid probs for the mixed 1000‑sample eval."""
    p = MIXED_DIR / "e2e_results.csv"
    df = pd.read_csv(p, encoding="utf-8")
    # The mixed CSV has true_label (0/1/2) and a column ai_used (bool).
    y = df["true_label"].to_numpy(dtype=int)
    # AI‑only subset: rows where an AI checkpoint was available.
    ai_mask = df["ai_used"].astype(bool).to_numpy()
    # For those rows we have AI probabilities p_ai_*; for all rows we have fused_*.
    p_ai = df[["p_ai_hate", "p_ai_offensive", "p_ai_clean"]].to_numpy(dtype=float)
    # Only for the ai_used rows the AI probs are meaningful; we will also compute hybrid on all 1000.
    p_fuse = df[["fused_hate", "fused_offensive", "fused_clean"]].to_numpy(dtype=float)

    return {"y": y, "ai_mask": ai_mask, "p_ai": p_ai, "p_fuse": p_fuse}


# --------------------------------------------------------------------------- #
# Main
# --------------------------------------------------------------------------- #
def main(argv: List[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Hybrid vs AI‑only calibration diagnostics"
    )
    parser.add_argument(
        "--out-dir",
        default=str(FUSION_DIR),
        help="Directory where output files will be written (default: outputs/evaluation/fusion)",
    )
    args = parser.parse_args(argv)

    out_dir = Path(args.out_dir)
    ensure_dir = out_dir.parents[0] if False else out_dir  # placeholder; we'll use mkdir below
    out_dir.mkdir(parents=True, exist_ok=True)

    # ------------------------------------------------------------------ #
    # Load data
    # ------------------------------------------------------------------ #
    vihsd = load_vihsd_fusion()
    mixed = load_mixed_e2e()

    # ------------------------------------------------------------------ #
    # Compute metrics for each variant on each dataset
    # ------------------------------------------------------------------ #
    results: Dict[str, Dict[str, Dict[str, float]]] = {}  # dataset -> variant -> metrics
    rows: List[Dict[str, any]] = []  # CSV rows

    datasets = {
        "vihsd": {"y": vihsd["y"], "p_ai": vihsd["p_ai"], "p_fuse": vihsd["p_fuse"], "n": vihsd["y"].shape[0]},
        "mixed": {
            "y": mixed["y"],
            "ai_mask": mixed["ai_mask"],
            "p_ai": mixed["p_ai"],
            "p_fuse": mixed["p_fuse"],
            "n": int(mixed["ai_mask"].sum()),  # number of AI‑only rows (941)
        },
    }

    # Determine which rows are AI‑only for mixed; for hybrid we use all rows.
    # Build AI‑only probs mask for mixed.
    mixed_ai_y = mixed["y"][mixed["ai_mask"]]
    mixed_ai_p = mixed["p_ai"][mixed["ai_mask"]]
    mixed_fuse_y = mixed["y"]  # all rows
    mixed_fuse_p = mixed["p_fuse"]

    for ds_name, ds in datasets.items():
        for variant, (probs, true_labels) in [
            ("AI‑only", (ds["p_ai"], ds["y"])),
            ("Hybrid", (ds["p_fuse"], ds["y"])),
        ]:
            # If dataset is mixed and variant is AI‑only, only use the ai_masked subset
            if ds_name == "mixed" and variant == "AI‑only":
                probs = mixed_ai_p
                true_labels = mixed_ai_y

            n = true_labels.shape[0]
            ece = compute_ece(probs, true_labels, n_bins=10)
            b = brier_score(probs, true_labels)
            nll = negative_log_likelihood(probs, true_labels)
            mean_conf = float(probs.max(axis=1).mean())

            # macro‑F1 from label predictions
            preds = probs.argmax(axis=1)
            from sklearn.metrics import f1_score
            macro_f1 = float(f1_score(true_labels, preds, average="macro"))

            key = f"{variant}"
            results.setdefault(ds_name, {})[key] = {
                "ece": ece,
                "brier": b,
                "nll": nll,
                "mean_conf": mean_conf,
                "macro_f1": macro_f1,
                "n": n,
            }

            rows.append(
                {
                    "model": "sensitiveai-vi" if ds_name == "vihsd" else "sensitiveai-vi-custom",
                    "variant": variant,
                    "dataset": ds_name,
                    "ece": ece,
                    "brier": b,
                    "nll": nll,
                    "mean_conf": mean_conf,
                    "macro_f1": macro_f1,
                    "n": n,
                }
            )

    # ------------------------------------------------------------------ #
    # Write JSON summary
    # ------------------------------------------------------------------ #
    summary_path = out_dir / "hybrid_calibration_summary.json"
    with summary_path.open("w", encoding="utf-8") as f:
        json.dump(results, f, ensure_ascii=False, indent=2)
    print(f"✅ JSON summary written to {summary_path}")

    # ------------------------------------------------------------------ #
    # Write CSV rows
    # ------------------------------------------------------------------ #
    csv_path = out_dir / "hybrid_calibration.csv"
    df_csv = pd.DataFrame(rows)
    df_csv.to_csv(csv_path, index=False, encoding="utf-8")
    print(f"✅ CSV written to {csv_path}")

    # ------------------------------------------------------------------ #
    # Write LaTeX table (ready to paste into the paper)
    # ------------------------------------------------------------------ #
    tex_path = out_dir / "hybrid_calibration.tex"
    # Build a small LaTeX table; the user can \input{...} or copy the block.
    lines: List[str] = []
    lines.append(r"\begin{table}[H]")
    lines.append(r"\centering")
    lines.append(r"\caption{Calibration diagnostics (ECE, Brier, NLL, mean confidence, macro‑F1) for AI‑only vs Hybrid on two datasets.}")
    lines.append(r"\label{tab:hybrid-calibration}")
    lines.append(r"\toprule")
    lines.append(r"Variant & Dataset & $n$ & ECE $\downarrow$ & Brier $\downarrow$ & NLL $\downarrow$ & mean conf. $\uparrow$ & Macro‑F1 $\uparrow$ \\")
    lines.append(r"\midrule")
    for ds_name in ["vihsd", "mixed"]:
        for variant in ["AI‑only", "Hybrid"]:
            r = results[ds_name][variant]
            dataset_label = (
                "ViHSD test (6 680)" if ds_name == "vihsd" else "Mixed 1000‑sample (941 AI‑only rows)"
            )
            lines.append(
                rf"{variant} & {dataset_label} & {r['n']} & {r['ece']:.3f} & {r['brier']:.4f} & {r['nll']:.4f} & {r['mean_conf']:.3f} & {r['macro_f1']:.4f} \\"
            )
    lines.append(r"\bottomrule")
    lines.append(r"\end{table}")
    tex_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"✅ LaTeX table written to {tex_path}")

    # ------------------------------------------------------------------ #
    # Generate reliability diagram (one figure, two panels: ViHSD + Mixed)
    # ------------------------------------------------------------------ #
    try:
        import sys
        sys.path.insert(0, str(PROJECT_ROOT))
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        from src.evaluation.plots import setup_style

        setup_style()
        n_bins = 10

        fig, axes = plt.subplots(1, 2, figsize=(12, 5), constrained_layout=True)

        # Left: ViHSD
        ax = axes[0]
        for variant, probs, true_lbl, label in [
            ("AI‑only", vihsd["p_ai"], vihsd["y"], "AI‑only"),
            ("Hybrid", vihsd["p_fuse"], vihsd["y"], "Hybrid"),
        ]:
            bins = reliability_bins(probs, true_lbl, n_bins=n_bins)
            xs = [b["confidence"] for b in bins if b["count"]]
            ys = [b["accuracy"] for b in bins if b["count"]]
            ax.plot(xs, ys, marker="o", linewidth=1.6, markersize=4, label=label)
        ax.plot([0, 1], [0, 1], color="grey", linestyle=":", linewidth=1.0)
        ax.set_xlim(0, 1)
        ax.set_ylim(0, 1)
        ax.set_xlabel("Confidence", fontsize=8)
        ax.set_ylabel("Accuracy", fontsize=8)
        ax.set_title(f"ViHSD test (ECE: {results['vihsd']['AI‑only']['ece']:.3f} vs {results['vihsd']['Hybrid']['ece']:.3f})", fontsize=9)
        ax.legend(fontsize=7)

        # Right: Mixed 1000
        ax2 = axes[1]
        for variant, probs, true_lbl, label in [
            ("AI‑only", mixed_ai_p, mixed_ai_y, "AI‑only"),
            ("Hybrid", mixed_fuse_p, mixed_fuse_y, "Hybrid"),
        ]:
            bins = reliability_bins(probs, true_lbl, n_bins=n_bins)
            xs = [b["confidence"] for b in bins if b["count"]]
            ys = [b["accuracy"] for b in bins if b["count"]]
            ax2.plot(xs, ys, marker="o", linewidth=1.6, markersize=4, label=label)
        ax2.plot([0, 1], [0, 1], color="grey", linestyle=":", linewidth=1.0)
        ax2.set_xlim(0, 1)
        ax2.set_ylim(0, 1)
        ax2.set_xlabel("Confidence", fontsize=8)
        ax2.set_ylabel("Accuracy", fontsize=8)
        ax2.set_title(f"Mixed 1000 sample (AI‑only rows n={mixed_ai_y.shape[0]})", fontsize=9)
        ax2.legend(fontsize=7)

        figure_path = PROJECT_ROOT / "papers" / "full_system_paper" / "figures" / "hybrid_reliability.png"
        figure_path.parent.mkdir(parents=True, exist_ok=True)
        fig.savefig(figure_path, dpi=200)
        plt.close(fig)
        print(f"✅ Reliability figure written to {figure_path}")
    except Exception as e:
        print(f"⚠️  Figure generation skipped: {e}")

    # ------------------------------------------------------------------ #
    # Print concise human‑readable summary
    # ------------------------------------------------------------------ #
    print("\n=== Calibration summary ===")
    for ds_name in ["vihsd", "mixed"]:
        print(f"\nDataset: {'ViHSD test' if ds_name == 'vihsd' else 'Mixed 1000 sample'}")
        for variant in ["AI‑only", "Hybrid"]:
            r = results[ds_name][variant]
            print(
                f"  {variant:8s}  n={r['n']:5d}  ECE={r['ece']:.3f}  Brier={r['brier']:.4f}  "
                f"NLL={r['nll']:.4f}  conf={r['mean_conf']:.3f}  Macro‑F1={r['macro_f1']:.4f}"
            )

    return 0


if __name__ == "__main__":
    raise SystemExit(main())