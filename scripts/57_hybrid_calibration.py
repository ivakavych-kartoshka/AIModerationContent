"""Calibration diagnostics for SensitiveAI hybrid vs AI-only.

Computes Expected Calibration Error (ECE), multiclass Brier score,
Negative Log-Likelihood (NLL) and mean confidence for two variants:

1. AI-only (argmax) – using the AI probability columns (prob_*).
2. Hybrid (fusion_per_channel_thresholds) – using fused probability columns
   (fused_hate, fused_offensive, fused_clean) from the frozen fusion run.

Reports results on two datasets:

  • ViHSD test split (6680 comments) – the frozen fusion predictions
    from ``outputs/evaluation/fusion/sensitiveai-vi-custom/fusion_predictions.csv``.
  • Mixed 1000‑sample end‑to‑end evaluation
    (outputs/evaluation/end_to_end_1000/e2e_results.csv).

The script writes:

* ``outputs/evaluation/fusion/hybrid_calibration_summary.json`` – JSON with per‑dataset
  metrics for both variants.
* ``outputs/evaluation/fusion/hybrid_calibration.csv`` – CSV rows
  ``model, variant, dataset, ece, brier, nll, mean_conf, macro_f1, n``.
* ``outputs/evaluation/fusion/hybrid_calibration.tex`` – LaTeX table that can be
  copied into the main paper (``papers/full_system_paper/sections/analysis.tex``)
  or into ``papers/full_system_paper/tables/``.

The LaTeX table follows the project style (``\\toprule`` / ``\\midrule`` /
``\\bottomrule`` from ``booktabs``, ``\\caption``, ``\\label``).  The figure
generated by the script is saved to ``papers/full_system_paper/figures/hybrid_reliability.png``
and can be included with ``\\includegraphics``.

Run::

    python scripts/57_hybrid_calibration.py

or with a different base directory::

    SENSITIVEAI_ROOT=/path/to/repo python scripts/57_hybrid_calibration.py
"""
