"""Step 8 - cross-split duplicate and de-leaked robustness check.

    python scripts/08_check_leakage.py

The official ViHSD partition reuses comments across train/dev/test.  This script
quantifies that overlap and re-scores every system on the subset of the test set
that has no exact duplicate in training or validation, all from the frozen
``test_predictions.csv`` files (no retraining).

Writes::

    outputs/evaluation/analysis/leakage_report.json
    outputs/evaluation/analysis/leakage_report.md
    papers/tables/duplicate_free.tex
"""

from __future__ import annotations

import json
import sys
from collections import Counter
from pathlib import Path

import pandas as pd
from sklearn.metrics import accuracy_score, f1_score

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from src.evaluation.analysis import MODEL_LABELS, MODEL_ORDER  # noqa: E402

PROJECT_ROOT = Path(__file__).resolve().parent.parent
SPLITS_DIR = PROJECT_ROOT / "data" / "splits"
PER_MODEL_DIR = PROJECT_ROOT / "outputs" / "evaluation" / "per_model"
ANALYSIS_DIR = PROJECT_ROOT / "outputs" / "evaluation" / "analysis"


def _key(series: pd.Series) -> pd.Series:
    return series.astype(str).str.strip().str.lower()


def write_duplicate_free_table(payload: dict, path: Path) -> Path:
    """LaTeX table scoring every system on the full and the duplicate-free test set."""
    systems = payload["systems"]
    labels = list(systems)

    def _best(key: str) -> float:
        return max(systems[label][key] for label in labels)

    best = {
        key: _best(key)
        for key in ("full_accuracy", "deleaked_accuracy", "full_macro_f1", "deleaked_macro_f1")
    }

    def _cell(value: float, key: str) -> str:
        text = f"{value:.4f}"
        return f"\\textbf{{{text}}}" if value == best[key] else text

    lines = [
        "% AUTO-GENERATED by scripts/08_check_leakage.py - do not edit by hand.",
        "\\begin{table}[h]",
        "\\centering",
        "\\footnotesize",
        "\\setlength{\\tabcolsep}{4pt}",
        "\\caption{Full vs.\\ the "
        f"{payload['deleaked_test']:,} duplicate-free test comments (Sect.~\\ref{{sec:dataset}}).  "
        "Accuracy drops for every system while macro-F1 and its ordering are essentially "
        "unchanged, so the conclusions do not rest on the overlap (Sect.~\\ref{sec:threats}).}",
        "\\label{tab:duplicate-free}",
        "\\begin{tabular}{lcccc}",
        "\\toprule",
        " & \\multicolumn{2}{c}{Accuracy} & \\multicolumn{2}{c}{Macro-F1} \\\\",
        "\\cmidrule(lr){2-3} \\cmidrule(lr){4-5}",
        "System & Full & Dup-free & Full & Dup-free \\\\",
        "\\midrule",
    ]
    for label in labels:
        s = systems[label]
        lines.append(
            f"{label} & {_cell(s['full_accuracy'], 'full_accuracy')} "
            f"& {_cell(s['deleaked_accuracy'], 'deleaked_accuracy')} "
            f"& {_cell(s['full_macro_f1'], 'full_macro_f1')} "
            f"& {_cell(s['deleaked_macro_f1'], 'deleaked_macro_f1')} \\\\"
        )
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")
    return path


def main() -> int:
    train = pd.read_csv(SPLITS_DIR / "train.csv")
    val = pd.read_csv(SPLITS_DIR / "validation.csv")
    test = pd.read_csv(SPLITS_DIR / "test.csv")

    train_keys, val_keys, test_keys = _key(train["text"]), _key(val["text"]), _key(test["text"])
    sets = {"train": set(train_keys), "validation": set(val_keys), "test": set(test_keys)}

    overlap = {
        "train_validation": len(sets["train"] & sets["validation"]),
        "train_test": len(sets["train"] & sets["test"]),
        "validation_test": len(sets["validation"] & sets["test"]),
    }

    merged = pd.concat(
        [train.assign(split="train"), val.assign(split="validation"), test.assign(split="test")],
        ignore_index=True,
    )
    merged["key"] = _key(merged["text"])
    per_key = merged.groupby("key")
    multi_split = per_key["split"].nunique() > 1
    multi_split_keys = set(per_key["split"].nunique()[multi_split].index)
    label_conflicts = int((per_key["label"].nunique()[per_key["split"].nunique() > 1] > 1).sum())

    leak_keys = sets["train"] | sets["validation"]
    leak_mask = test_keys.isin(leak_keys)
    leaked = int(leak_mask.sum())
    total = int(len(test))

    systems: dict[str, dict] = {}
    for name in MODEL_ORDER:
        frame = pd.read_csv(PER_MODEL_DIR / name / "test_predictions.csv")
        if not _key(frame["text"]).equals(test_keys):
            raise ValueError(f"{name}: predictions are not aligned with the test split")
        y = frame["true_label_id"].to_numpy()
        p = frame["pred_label_id"].to_numpy()
        systems[MODEL_LABELS[name]] = {
            "full_macro_f1": float(f1_score(y, p, average="macro")),
            "full_accuracy": float(accuracy_score(y, p)),
            "deleaked_macro_f1": float(f1_score(y[~leak_mask], p[~leak_mask], average="macro")),
            "deleaked_accuracy": float(accuracy_score(y[~leak_mask], p[~leak_mask])),
            "leaked_macro_f1": float(f1_score(y[leak_mask], p[leak_mask], average="macro")),
        }

    payload = {
        "test_total": total,
        "test_leaked": leaked,
        "test_leaked_fraction": leaked / total,
        "deleaked_test": total - leaked,
        "cross_split_distinct_strings": overlap,
        "distinct_strings_in_multiple_splits": len(multi_split_keys),
        "distinct_strings_with_conflicting_labels": label_conflicts,
        "systems": systems,
    }

    ANALYSIS_DIR.mkdir(parents=True, exist_ok=True)
    (ANALYSIS_DIR / "leakage_report.json").write_text(
        json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8"
    )

    lines = [
        "# Cross-split duplication and de-leaked robustness",
        "",
        f"- test comments: {total:,}",
        f"- test comments with an exact duplicate in train or validation: "
        f"{leaked:,} ({100 * leaked / total:.1f}%)",
        f"- de-leaked test subset: {total - leaked:,}",
        f"- distinct strings in >1 split: {len(multi_split_keys):,} "
        f"(label-conflicting: {label_conflicts:,})",
        f"- pairwise distinct-string overlaps: {overlap}",
        "",
        "| System | Full macro-F1 | De-leaked macro-F1 | Leaked-only macro-F1 | Full acc. | De-leaked acc. |",
        "|---|---|---|---|---|---|",
    ]
    for label, s in systems.items():
        lines.append(
            f"| {label} | {s['full_macro_f1']:.4f} | {s['deleaked_macro_f1']:.4f} "
            f"| {s['leaked_macro_f1']:.4f} | {s['full_accuracy']:.4f} "
            f"| {s['deleaked_accuracy']:.4f} |"
        )
    (ANALYSIS_DIR / "leakage_report.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

    table = write_duplicate_free_table(payload, PROJECT_ROOT / "papers" / "tables" / "duplicate_free.tex")
    mirror = PROJECT_ROOT / "outputs" / "paper" / "tables" / "duplicate_free.tex"
    mirror.parent.mkdir(parents=True, exist_ok=True)
    mirror.write_bytes(table.read_bytes())

    print(
        f"leaked {leaked}/{total} ({100 * leaked / total:.1f}%); "
        f"de-leaked test = {total - leaked}; report -> {ANALYSIS_DIR / 'leakage_report.md'}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
